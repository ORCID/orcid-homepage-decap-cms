#!/usr/bin/env node
/**
 * One-off bootstrap: read the homepage that is live today and write it out as
 * this repository's source of truth.
 *
 * Not part of CI and not expected to run twice. It exists so the first version
 * of content/home.en.json is exactly what visitors see rather than a retyped
 * approximation, and so the seeded translations are the ones already published,
 * with all their machine-translation flaws, instead of empty strings.
 *
 * The live pages are the WordPress clone, so this reads structure that only
 * that pipeline produces. Once the clone is retired this script has no purpose.
 *
 *   node scripts/seed-from-live.mjs [--base https://homepage-prod.orcid.org]
 */
import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { parse } from 'node-html-parser'

const repoRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..'
)

const LOCALES = [
  'ar',
  'cs',
  'de',
  'es',
  'fr',
  'it',
  'ja',
  'ko',
  'pl',
  'pt',
  'ru',
  'tr',
  'zh-CN',
  'zh-TW',
]

/** Ids for the closing section, which has no natural label to slugify. */
const INTEGRATE_IDS = ['hub', 'certified-service-providers', 'getting-started']

function slug(text) {
  return text
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/&amp;|&/g, ' ')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .split('-')
    .slice(0, 5)
    .join('-')
}

/** Readable filename for a WordPress asset: drop the fingerprint and the size. */
function imageName(src) {
  const base = path.basename(src)
  const extension = path.extname(base)
  const stem = path
    .basename(base, extension)
    .replace(/-[0-9a-f]{10}$/, '')
    .split(/_(?:20dp|40dp|clearer)/)[0]
    .replace(/_\d+x\d+$/, '')
  return `${stem}${extension}`
}

/** WordPress inline markup -> the markdown-lite subset the renderer accepts. */
function toMarkdownLite(node) {
  let out = ''

  for (const child of node.childNodes) {
    if (child.nodeType === 3) {
      out += child.rawText
      continue
    }
    const tag = child.rawTagName?.toLowerCase()
    if (tag === 'a') {
      const href = child.getAttribute('href') ?? ''
      const text = toMarkdownLite(child).trim()
      out += href ? `[${text}](${href})` : text
    } else if (tag === 'strong' || tag === 'b') {
      out += `**${toMarkdownLite(child).trim()}**`
    } else if (tag === 'br') {
      out += ' '
    } else {
      out += toMarkdownLite(child)
    }
  }

  return out
}

function text(node) {
  return decode(node.structuredText ?? node.text)
    .replace(/\s+/g, ' ')
    .trim()
}

function decode(value) {
  return value
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&#8217;|&rsquo;/g, '’')
    .replace(/&#8216;|&lsquo;/g, '‘')
    .replace(/&#8220;|&ldquo;/g, '“')
    .replace(/&#8221;|&rdquo;/g, '”')
    .replace(/&#8211;|&ndash;/g, '–')
    .replace(/&#8212;|&mdash;/g, '—')
    .replace(/&#8230;|&hellip;/g, '…')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#0?39;|&#x27;|&apos;/g, "'")
}

function prose(node) {
  return decode(toMarkdownLite(node)).replace(/\s+/g, ' ').trim()
}

/**
 * Pull the page apart into the shape of the schema. The live markup is
 * generated by a WordPress block theme, so this leans on the block class names
 * rather than on document order wherever it can.
 */
function parsePage(html) {
  const root = parse(html)

  const labels = root
    .querySelectorAll('.blablablocks-tabs-buttons li')
    .map((li) => text(li))

  const panels = root.querySelectorAll('.blablablocks-tab-content')

  const audiences = panels.map((panel, index) => {
    const label = labels[index] ?? `Audience ${index + 1}`
    const background = panel.querySelector(
      'img.wp-block-cover__image-background'
    )
    const paragraphs = panel.querySelectorAll('p')
    const headings = panel.querySelectorAll('h2')
    // Every image in the panel except the cover background is a feature icon.
    const icons = panel
      .querySelectorAll('img')
      .filter(
        (img) => !img.classNames.includes('wp-block-cover__image-background')
      )

    const features = headings.map((heading, featureIndex) => ({
      id: slug(text(heading)),
      icon: `images/${imageName(icons[featureIndex]?.getAttribute('src') ?? '')}`,
      title: text(heading),
      body: prose(paragraphs[featureIndex + 1]),
    }))

    return {
      id: slug(label),
      label,
      background: `images/${imageName(background?.getAttribute('src') ?? '')}`,
      intro: prose(paragraphs[0]),
      features,
      icons: icons.map((i) => i.getAttribute('src')),
    }
  })

  // Everything after the tabs: the featured video, then the closing section.
  const tail = root.querySelectorAll('h2, h3, p, iframe')
  const newsTitleIndex = tail.findIndex(
    (n) => n.rawTagName === 'h2' && !isInsideTabs(n)
  )
  const newsTitle = tail[newsTitleIndex]
  const kicker = previousParagraph(tail, newsTitleIndex)
  const newsBody = tail
    .slice(newsTitleIndex + 1)
    .find((n) => n.rawTagName === 'p')
  const iframe = root.querySelector('iframe')
  const vimeoId = iframe?.getAttribute('src')?.match(/video\/(\d+)/)?.[1] ?? '0'

  const integrateTitle = tail.find((n) => n.rawTagName === 'h3')
  const integrateIndex = tail.indexOf(integrateTitle)
  const paragraphs = tail
    .slice(integrateIndex + 1)
    .filter((n) => n.rawTagName === 'p')
    .slice(0, INTEGRATE_IDS.length)

  return {
    hero: { title: text(root.querySelector('h1')) },
    audiences,
    featuredNews: {
      kicker: kicker ? text(kicker) : 'FEATURED NEWS',
      title: text(newsTitle),
      body: prose(newsBody),
      vimeoId,
    },
    integrate: {
      title: text(integrateTitle),
      paragraphs: paragraphs.map((p, i) => ({
        id: INTEGRATE_IDS[i] ?? `paragraph-${i + 1}`,
        body: prose(p),
      })),
    },
  }
}

function isInsideTabs(node) {
  for (let cursor = node.parentNode; cursor; cursor = cursor.parentNode) {
    if (cursor.classNames?.includes?.('blablablocks-tabs')) return true
  }
  return false
}

function previousParagraph(nodes, index) {
  for (let i = index - 1; i >= 0; i -= 1) {
    if (nodes[i].rawTagName === 'p' && !isInsideTabs(nodes[i])) return nodes[i]
  }
  return null
}

async function fetchText(url) {
  const response = await fetch(url)
  if (!response.ok) throw new Error(`${url} -> HTTP ${response.status}`)
  return response.text()
}

async function main() {
  const args = process.argv.slice(2)
  const baseIndex = args.indexOf('--base')
  const base =
    baseIndex === -1 ? 'https://homepage-prod.orcid.org' : args[baseIndex + 1]

  process.stdout.write(`Reading ${base}/index.html\n`)
  const english = parsePage(await fetchText(`${base}/index.html`))

  // Download every referenced image once, under its cleaned-up name.
  const imagesDir = path.join(repoRoot, 'content/images')
  await mkdir(imagesDir, { recursive: true })
  const downloaded = new Set()

  const sources = new Set()
  for (const audience of english.audiences) {
    for (const src of audience.icons) sources.add(src)
  }
  const backgroundSource = (await fetchText(`${base}/index.html`)).match(
    /src="(\.\/assets\/kaya[^"]+)"/
  )?.[1]
  if (backgroundSource) sources.add(backgroundSource)

  for (const src of sources) {
    const name = imageName(src)
    if (downloaded.has(name)) continue
    const url = new URL(src.replace(/^\.\//, ''), `${base}/`).toString()
    const response = await fetch(url)
    if (!response.ok) {
      throw new Error(`image ${url} -> HTTP ${response.status}`)
    }
    await writeFile(
      path.join(imagesDir, name),
      Buffer.from(await response.arrayBuffer())
    )
    downloaded.add(name)
    process.stdout.write(`  image ${name}\n`)
  }

  for (const audience of english.audiences) delete audience.icons

  const content = { schemaVersion: 1, ...english }
  await writeFile(
    path.join(repoRoot, 'content/home.en.json'),
    `${JSON.stringify(content, null, 2)}\n`
  )
  process.stdout.write(`Wrote content/home.en.json\n`)

  // The translated pages have the same block structure, so each string is taken
  // from the same position and filed under the English id.
  await mkdir(path.join(repoRoot, 'i18n'), { recursive: true })
  for (const locale of LOCALES) {
    const translated = parsePage(
      await fetchText(`${base}/index-${locale}.html`)
    )
    const strings = {
      hero: { title: translated.hero.title },
      audiences: Object.fromEntries(
        english.audiences.map((audience, index) => {
          const other = translated.audiences[index]
          return [
            audience.id,
            {
              label: other?.label ?? audience.label,
              intro: other?.intro ?? audience.intro,
              features: Object.fromEntries(
                audience.features.map((feature, featureIndex) => [
                  feature.id,
                  {
                    title:
                      other?.features?.[featureIndex]?.title ?? feature.title,
                    body: other?.features?.[featureIndex]?.body ?? feature.body,
                  },
                ])
              ),
            },
          ]
        })
      ),
      featuredNews: {
        kicker: translated.featuredNews.kicker,
        title: translated.featuredNews.title,
        body: translated.featuredNews.body,
      },
      integrate: {
        title: translated.integrate.title,
        paragraphs: Object.fromEntries(
          english.integrate.paragraphs.map((paragraph, index) => [
            paragraph.id,
            {
              body:
                translated.integrate.paragraphs[index]?.body ?? paragraph.body,
            },
          ])
        ),
      },
    }

    await writeFile(
      path.join(repoRoot, `i18n/home.${locale}.json`),
      `${JSON.stringify(strings, null, 2)}\n`
    )
    process.stdout.write(`  locale ${locale}\n`)
  }
}

main().catch((problem) => {
  process.stderr.write(`${problem.stack}\n`)
  process.exit(1)
})
